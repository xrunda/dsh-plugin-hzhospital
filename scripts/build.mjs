import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'))
const png = readFileSync(new URL('assets/hztxt_logo.png', root))
if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' ||
    png.readUInt32BE(16) !== 4140 || png.readUInt32BE(20) !== 640) {
  throw new Error('Logo format/dimensions changed; update the crop proportions before building.')
}
const source = readFileSync(new URL('src/client.cjs', root), 'utf8')
const body = source.replace('__HOSPITAL_LOGO_DATA_URI__', JSON.stringify(`data:image/png;base64,${png.toString('base64')}`))
const output = `// Generated by scripts/build.mjs. Commit this file for offline Git installation.\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {\nconst module = { exports: {} };\nconst exports = module.exports;\n${body}\nreturn module.exports;\n} });\n`
const target = new URL('lib/client.js', root)
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('lib/client.js is stale: run npm run build')
  console.log('Committed client bundle is up to date.')
} else {
  mkdirSync(fileURLToPath(new URL('lib/', root)), { recursive: true })
  writeFileSync(target, output)
  console.log('Built lib/client.js with embedded local Logo; no external dependencies.')
}
